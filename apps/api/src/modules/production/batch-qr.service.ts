import crypto from 'crypto';
import { AuditAction } from '@prisma/client';
import { prisma } from '../../services/prisma.service';
import { AppError } from '../../middleware/error.middleware';
import { AuditService } from '../../services/audit.service';
import { AuditMeta } from '../master-data/master-data.utils';
import { assertWarehouseAccess } from '../inventory/inventory.utils';
import { SyncUserContext } from '../sync/sync.service';

export class BatchQrService {
  private static async getBatchForQr(batchId: string, user: SyncUserContext) {
    const batch = await prisma.productionBatch.findUnique({
      where: { id: batchId },
      include: {
        product: { select: { id: true, code: true, name: true } },
        productVariant: { select: { id: true, sku: true, name: true } },
        uom: { select: { code: true, symbol: true } },
        warehouse: {
          select: {
            id: true,
            code: true,
            name: true,
            factory: { select: { id: true, code: true, name: true } },
          },
        },
      },
    });
    if (!batch) {
      throw new AppError('Production batch not found.', 404);
    }
    await assertWarehouseAccess(user, batch.warehouseId, 'READ');
    return batch;
  }

  static async generateOrGetQr(batchId: string, user: SyncUserContext, meta: AuditMeta) {
    const batch = await this.getBatchForQr(batchId, user);

    let qrRef = await prisma.batchQrReference.findFirst({
      where: { productionBatchId: batchId, isActive: true },
      orderBy: { createdAt: 'desc' },
    });

    if (!qrRef) {
      const referenceToken = crypto.randomBytes(18).toString('base64url');
      qrRef = await prisma.batchQrReference.create({
        data: {
          productionBatchId: batchId,
          referenceToken,
          isActive: true,
          createdById: user.userId,
        },
      });

      await AuditService.log({
        userId: user.userId,
        action: AuditAction.CREATE,
        entityType: 'BatchQrReference',
        entityId: qrRef.id,
        newState: { productionBatchId: batchId, referenceToken },
        ipAddress: meta.ipAddress,
        userAgent: meta.userAgent,
        remarks: `Generated QR traceability reference for batch ${batch.batchNumber}`,
      });
    }

    const companyCfg = await prisma.systemConfig.findUnique({
      where: { key: 'COMPANY_NAME' },
      select: { value: true },
    });

    return {
      referenceToken: qrRef.referenceToken,
      tracePath: `/trace/batch/${qrRef.referenceToken}`,
      isActive: qrRef.isActive,
      createdAt: qrRef.createdAt.toISOString(),
      labelData: {
        companyName: companyCfg?.value || 'FoodFactory ERP',
        productName: batch.product.name,
        variantName: batch.productVariant.name,
        sku: batch.productVariant.sku,
        batchNumber: batch.batchNumber,
        manufacturingDate: batch.manufacturingDate?.toISOString() ?? null,
        expiryDate: batch.expiryDate?.toISOString() ?? null,
        plannedQuantity: batch.plannedQuantity.toFixed(2),
        actualGoodQuantity: batch.actualGoodQuantity.toFixed(2),
        uomSymbol: batch.uom.symbol,
        factoryName: batch.warehouse.factory?.name ?? batch.warehouse.name,
      },
    };
  }

  static async revokeAndRegenerateQr(
    batchId: string,
    reason: string,
    user: SyncUserContext,
    meta: AuditMeta,
  ) {
    const batch = await this.getBatchForQr(batchId, user);

    await prisma.batchQrReference.updateMany({
      where: { productionBatchId: batchId, isActive: true },
      data: {
        isActive: false,
        revokedAt: new Date(),
        revokedById: user.userId,
        revocationReason: reason || 'Regenerated by authorized user',
      },
    });

    await AuditService.log({
      userId: user.userId,
      action: AuditAction.UPDATE,
      entityType: 'BatchQrReference',
      entityId: batchId,
      remarks: `Revoked active QR reference for batch ${batch.batchNumber}: ${reason || 'Regenerated'}`,
      ipAddress: meta.ipAddress,
      userAgent: meta.userAgent,
    });

    return this.generateOrGetQr(batchId, user, meta);
  }

  static async resolveQrTraceability(referenceToken: string, user: SyncUserContext) {
    const cleanToken = referenceToken.trim();
    if (!cleanToken) {
      throw new AppError('Invalid QR reference.', 400);
    }

    const qrRef = await prisma.batchQrReference.findUnique({
      where: { referenceToken: cleanToken },
    });

    if (!qrRef) {
      throw new AppError('QR reference not found or invalid.', 404);
    }
    if (!qrRef.isActive) {
      throw new AppError('This QR reference has been revoked.', 410);
    }

    const batch = await prisma.productionBatch.findUnique({
      where: { id: qrRef.productionBatchId },
      include: {
        product: {
          include: { category: { select: { name: true } } },
        },
        productVariant: { select: { id: true, sku: true, name: true } },
        bom: { select: { id: true, code: true, name: true } },
        bomVersion: { select: { id: true, versionNumber: true, yieldPercentage: true } },
        workOrder: { select: { id: true, workOrderNumber: true, status: true, createdAt: true } },
        warehouse: {
          select: {
            id: true,
            code: true,
            name: true,
            factory: { select: { id: true, code: true, name: true } },
          },
        },
        uom: { select: { code: true, symbol: true } },
        consumptions: {
          include: {
            inventoryItem: { select: { id: true, code: true, name: true, itemType: true } },
            batch: { select: { id: true, batchNumber: true, expiryDate: true } },
            uom: { select: { symbol: true } },
          },
        },
        returns: {
          include: {
            inventoryItem: { select: { id: true, code: true, name: true } },
            batch: { select: { id: true, batchNumber: true } },
            uom: { select: { symbol: true } },
          },
        },
        executionEntries: {
          orderBy: { createdAt: 'asc' },
          take: 50,
          select: {
            id: true,
            entryType: true,
            goodQuantity: true,
            rejectedQuantity: true,
            wastageQuantity: true,
            notes: true,
            createdAt: true,
          },
        },
        qualityInspection: {
          select: {
            id: true,
            inspectionNumber: true,
            decision: true,
            inspectedQuantity: true,
            goodQuantity: true,
            rejectedQuantity: true,
            inspectedAt: true,
            createdAt: true,
          },
        },
        finishedGoodsBatch: {
          select: {
            id: true,
            batchNumber: true,
            qualityStatus: true,
            manufacturingDate: true,
            expiryDate: true,
          },
        },
        costing: {
          select: {
            id: true,
            status: true,
            standardTotalCost: true,
            finalizedAt: true,
          },
        },
      },
    });

    if (!batch) {
      throw new AppError('Production batch linked to QR was not found.', 404);
    }

    // Enforce warehouse & factory scope
    await assertWarehouseAccess(user, batch.warehouseId, 'READ');

    const canViewCosting =
      user.roles.includes('OWNER') || user.permissions.includes('production.costing.read');
    const canViewSales =
      user.roles.includes('OWNER') || user.permissions.includes('sales.orders.read');

    const [fgTransactions, dispatchRefs] = await Promise.all([
      batch.finishedGoodsBatchId
        ? prisma.inventoryTransactionLine.findMany({
            where: { batchId: batch.finishedGoodsBatchId },
            take: 20,
            orderBy: { createdAt: 'desc' },
            select: {
              id: true,
              quantity: true,
              transaction: {
                select: {
                  id: true,
                  transactionNumber: true,
                  transactionType: true,
                  transactionDate: true,
                  warehouse: { select: { code: true, name: true } },
                },
              },
            },
          })
        : [],
      batch.finishedGoodsBatchId && canViewSales
        ? prisma.inventoryIssueLine.findMany({
            where: { batchId: batch.finishedGoodsBatchId },
            take: 10,
            select: {
              id: true,
              baseQuantity: true,
              issue: {
                select: {
                  id: true,
                  issueNumber: true,
                  issueDate: true,
                  purpose: true,
                },
              },
            },
          })
        : [],
    ]);

    const timeline: Array<{ stage: string; title: string; detail: string; timestamp: string }> = [
      {
        stage: 'WORK_ORDER',
        title: `Work Order ${batch.workOrder.workOrderNumber}`,
        detail: `Status: ${batch.workOrder.status}`,
        timestamp: batch.workOrder.createdAt.toISOString(),
      },
      {
        stage: 'PRODUCTION_BATCH',
        title: `Production Batch ${batch.batchNumber}`,
        detail: `BOM ${batch.bom.code} v${batch.bomVersion.versionNumber} • Status: ${batch.status}`,
        timestamp: batch.createdAt.toISOString(),
      },
    ];

    for (const c of batch.consumptions) {
      timeline.push({
        stage: 'RAW_MATERIAL_CONSUMPTION',
        title: `Consumed ${c.inventoryItem.name} (${c.inventoryItem.code})`,
        detail: `Source Batch: ${c.batch?.batchNumber ?? 'Unbatched'} • Qty: ${c.baseQuantity.toFixed(4)} ${c.uom.symbol}`,
        timestamp: c.consumedAt.toISOString(),
      });
    }

    if (batch.qualityInspection) {
      timeline.push({
        stage: 'QUALITY_INSPECTION',
        title: `Quality Inspection ${batch.qualityInspection.inspectionNumber}`,
        detail: `Decision: ${batch.qualityInspection.decision}`,
        timestamp: (
          batch.qualityInspection.inspectedAt ?? batch.qualityInspection.createdAt
        ).toISOString(),
      });
    }

    for (const tx of fgTransactions) {
      timeline.push({
        stage: 'INVENTORY_MOVEMENT',
        title: `${tx.transaction.transactionType}: ${tx.transaction.transactionNumber}`,
        detail: `${tx.transaction.warehouse.name} • Qty: ${tx.quantity.toFixed(4)}`,
        timestamp: tx.transaction.transactionDate.toISOString(),
      });
    }

    timeline.sort((a, b) => a.timestamp.localeCompare(b.timestamp));

    return {
      referenceToken: qrRef.referenceToken,
      batchIdentity: {
        id: batch.id,
        batchNumber: batch.batchNumber,
        status: batch.status,
        qualityStatus: batch.finishedGoodsBatch?.qualityStatus ?? 'PENDING_INSPECTION',
        productName: batch.product.name,
        productCode: batch.product.code,
        categoryName: batch.product.category.name,
        variantName: batch.productVariant.name,
        sku: batch.productVariant.sku,
        manufacturingDate: batch.manufacturingDate?.toISOString() ?? null,
        expiryDate: batch.expiryDate?.toISOString() ?? null,
        workOrderNumber: batch.workOrder.workOrderNumber,
        workOrderId: batch.workOrder.id,
        warehouseName: batch.warehouse.name,
        factoryName: batch.warehouse.factory?.name ?? batch.warehouse.name,
        plannedQuantity: batch.plannedQuantity.toFixed(4),
        actualGoodQuantity: batch.actualGoodQuantity.toFixed(4),
        rejectedQuantity: batch.rejectedQuantity.toFixed(4),
        wastageQuantity: batch.wastageQuantity.toFixed(4),
        uomSymbol: batch.uom.symbol,
      },
      recipeAndInputs: {
        bomCode: batch.bom.code,
        bomName: batch.bom.name,
        bomVersionNumber: batch.bomVersion.versionNumber,
        consumptions: batch.consumptions.map(c => ({
          id: c.id,
          itemCode: c.inventoryItem.code,
          itemName: c.inventoryItem.name,
          itemType: c.inventoryItem.itemType,
          sourceBatchNumber: c.batch?.batchNumber ?? 'Unbatched',
          quantity: c.baseQuantity.toFixed(4),
          uomSymbol: c.uom.symbol,
        })),
        returns: batch.returns.map(r => ({
          id: r.id,
          itemCode: r.inventoryItem.code,
          itemName: r.inventoryItem.name,
          sourceBatchNumber: r.batch?.batchNumber ?? 'Unbatched',
          quantity: r.baseQuantity.toFixed(4),
          uomSymbol: r.uom.symbol,
        })),
      },
      productionHistory: {
        actualYieldPercent: batch.actualYieldPercent.toFixed(2),
        entries: batch.executionEntries.map(e => ({
          id: e.id,
          entryType: e.entryType,
          goodQuantity: e.goodQuantity?.toFixed(4) ?? null,
          rejectedQuantity: e.rejectedQuantity?.toFixed(4) ?? null,
          wastageQuantity: e.wastageQuantity?.toFixed(4) ?? null,
          notes: e.notes,
          createdAt: e.createdAt.toISOString(),
        })),
        costing:
          canViewCosting && batch.costing
            ? {
                status: batch.costing.status,
                totalProductionCost: batch.costing.standardTotalCost.toFixed(2),
                costPerGoodUnit: batch.actualGoodQuantity.gt(0)
                  ? batch.costing.standardTotalCost.div(batch.actualGoodQuantity).toFixed(2)
                  : '0.00',
                finalizedAt: batch.costing.finalizedAt?.toISOString() ?? null,
              }
            : null,
      },
      qualityHistory: batch.qualityInspection
        ? {
            inspectionNumber: batch.qualityInspection.inspectionNumber,
            decision: batch.qualityInspection.decision,
            acceptedQuantity: batch.qualityInspection.goodQuantity.toFixed(4),
            rejectedQuantity: batch.qualityInspection.rejectedQuantity.toFixed(4),
            quarantinedQuantity: '0.0000',
            inspectedAt: batch.qualityInspection.inspectedAt?.toISOString() ?? null,
          }
        : null,
      finishedGoodsAndMovement: {
        finishedGoodsBatchNumber: batch.finishedGoodsBatch?.batchNumber ?? null,
        movements: fgTransactions.map(t => ({
          id: t.id,
          transactionNumber: t.transaction.transactionNumber,
          transactionType: t.transaction.transactionType,
          warehouseName: t.transaction.warehouse.name,
          quantity: t.quantity.toFixed(4),
          transactionDate: t.transaction.transactionDate.toISOString(),
        })),
        dispatches: dispatchRefs.map(d => ({
          fulfillmentNumber: d.issue.purpose ?? d.issue.issueNumber,
          salesOrderNumber: d.issue.issueNumber,
          salesOrderId: d.issue.id,
          issueNumber: d.issue.issueNumber,
        })),
      },
      timeline,
    };
  }
}
